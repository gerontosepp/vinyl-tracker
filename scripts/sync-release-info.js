#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

// Resolve project root (parent directory of scripts/)
const ROOT_DIR = path.resolve(__dirname, '..');
const RELEASE_INFO_PATH = path.join(ROOT_DIR, 'docs', 'Release-Info.md');
const PACKAGE_JSON_PATH = path.join(ROOT_DIR, 'frontend', 'package.json');
const TARGET_TS_PATH = path.join(ROOT_DIR, 'frontend', 'src', 'app', 'core', 'constants', 'release-info.data.ts');
const TARGET_JSON_PATH = path.join(ROOT_DIR, 'frontend', 'public', 'assets', 'release-info.json');

if (!fs.existsSync(RELEASE_INFO_PATH)) {
  console.error(`Error: Release-Info.md not found at ${RELEASE_INFO_PATH}`);
  process.exit(1);
}

const currentVersion = fs.existsSync(PACKAGE_JSON_PATH)
  ? JSON.parse(fs.readFileSync(PACKAGE_JSON_PATH, 'utf8')).version
  : '0.7.0';

const content = fs.readFileSync(RELEASE_INFO_PATH, 'utf8');
const sections = content.split(/\n(?=## )/);

function detectType(title) {
  const lower = title.toLowerCase();
  if (lower.startsWith('fix:') || lower.startsWith('bugfix:') || lower.includes('behebung') || lower.includes('fehler')) {
    return { type: 'fix', label: 'Fix' };
  }
  if (lower.startsWith('security') || lower.includes('rate limiting') || lower.includes('sicherheit')) {
    return { type: 'security', label: 'Security' };
  }
  if (lower.startsWith('devops') || lower.startsWith('docker') || lower.startsWith('ci/cd') || lower.includes('dependency') || lower.includes('build-')) {
    return { type: 'chore', label: 'DevOps / Tooling' };
  }
  if (lower.startsWith('perf') || lower.includes('performance') || lower.includes('optimierung')) {
    return { type: 'perf', label: 'Perf' };
  }
  if (lower.startsWith('refactor') || lower.includes('refactoring') || lower.includes('architektur')) {
    return { type: 'refactor', label: 'Refactor' };
  }
  if (lower.startsWith('dokumentation') || lower.startsWith('docs')) {
    return { type: 'docs', label: 'Docs' };
  }
  return { type: 'feat', label: 'Feature' };
}

function parseSection(sec) {
  const lines = sec.trim().split('\n');
  const header = lines[0].replace(/^##\s+/, '').trim();
  if (header.startsWith('#') || header.length === 0) return null;

  let version = header;
  let date = '';
  let tag = '';

  const versionMatch = header.match(/^(v[\d\.]+)(?:\s*\(([\d-]+)\))?(?:\s*[–-]\s*(.*))?$/);
  if (versionMatch) {
    version = versionMatch[1];
    date = versionMatch[2] || '';
    tag = versionMatch[3] || '';
  } else {
    const unreleasedMatch = header.match(/^Unreleased/i);
    if (unreleasedMatch) {
      version = 'Unreleased';
      tag = 'In Entwicklung';
    }
  }

  const cleanVersion = version.replace(/^v/, '');
  const isCurrent = cleanVersion === currentVersion;
  const isUnreleased = version.toLowerCase() === 'unreleased';

  const items = [];
  let currentItem = null;

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i];
    const boldMatch = line.match(/^-\s+\*\*(.+?)\*\*:\s*(.*)$/);

    if (boldMatch) {
      const title = boldMatch[1].trim();
      const summary = boldMatch[2].trim();
      const { type, label } = detectType(title);
      currentItem = {
        title,
        type,
        typeLabel: label,
        summary: summary || undefined,
        details: []
      };
      items.push(currentItem);
    } else {
      const detailMatch = line.match(/^\s+-\s+(.+)$/);
      if (detailMatch && currentItem) {
        currentItem.details.push(detailMatch[1].trim());
      } else if (line.trim().startsWith('- ') && !boldMatch) {
        const text = line.trim().replace(/^-\s+/, '').trim();
        if (text) {
          const { type, label } = detectType(text);
          currentItem = {
            title: text,
            type,
            typeLabel: label,
            details: []
          };
          items.push(currentItem);
        }
      }
    }
  }

  return {
    version,
    rawHeader: header,
    date: date || undefined,
    tag: tag || undefined,
    isCurrent,
    isUnreleased,
    items
  };
}

const releases = sections.map(parseSection).filter(Boolean);

// Ensure directories exist
fs.mkdirSync(path.dirname(TARGET_TS_PATH), { recursive: true });
fs.mkdirSync(path.dirname(TARGET_JSON_PATH), { recursive: true });

// 1. Write TypeScript data file
const tsContent = `// Automatically generated from docs/Release-Info.md by scripts/sync-release-info.js
// Do not edit this file directly; update docs/Release-Info.md and re-run sync.
import { ReleaseEntry } from '../models/release-info.model';

// Application version from frontend/package.json – single source for all version badges.
export const APP_VERSION = '${currentVersion}';

export const RELEASE_INFO_DATA: ReleaseEntry[] = ${JSON.stringify(releases, null, 2)};
`;

fs.writeFileSync(TARGET_TS_PATH, tsContent, 'utf8');
console.log(`✓ Generated ${TARGET_TS_PATH} (${releases.length} releases)`);

// 2. Write JSON asset file
fs.writeFileSync(TARGET_JSON_PATH, JSON.stringify(releases, null, 2), 'utf8');
console.log(`✓ Generated ${TARGET_JSON_PATH}`);
